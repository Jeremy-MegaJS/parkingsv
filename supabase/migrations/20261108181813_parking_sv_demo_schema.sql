-- Parking SV academic demo schema.
-- Public listing data is read-only; account profiles are synthetic and isolated by RLS.

revoke execute on function public.rls_auto_enable() from public, anon, authenticated;

create or replace function public.current_auth_email()
returns text language sql stable
set search_path = pg_catalog
as $$ select nullif(lower(auth.jwt() ->> 'email'), '') $$;

create table if not exists public.users (
 id bigint generated by default as identity primary key,
 full_name varchar(100) not null,
 email varchar(150) not null unique,
 password_hash varchar(255),
 profile_picture text not null default '/parkingsv/default-avatar.jpeg',
 phone_number varchar(20),
 date_of_birth date,
 business_name varchar(100),
 user_type text not null default 'customer' check (user_type in ('customer','owner')),
 created_at timestamptz not null default now(),
 location_permission boolean not null default false,
 latitude numeric(10,8),
 longitude numeric(11,8),
 penalty_count integer not null default 0,
 is_penalized boolean not null default false,
 email_verified boolean not null default true,
 email_verified_at timestamptz default now(),
 last_login timestamptz,
 is_premium boolean not null default false,
 premium_until timestamptz
);
create table if not exists public.locations (
 id bigint generated by default as identity primary key,
 department varchar(50) not null,
 municipality varchar(50) not null,
 street_address varchar(120) not null,
 reference_address varchar(180) not null,
 waze_link text not null default '',
 google_maps_link text not null default '',
 latitude numeric(10,8),
 longitude numeric(11,8)
);
create table if not exists public.parking_categories (
 id smallint generated by default as identity primary key,
 name varchar(50) not null,
 description text not null
);
create table if not exists public.vehicle_types (
 id smallint generated by default as identity primary key,
 category_key varchar(30) not null unique,
 category_name varchar(50) not null,
 icon varchar(30) not null,
 description text not null
);
create table if not exists public.services (
 id smallint generated by default as identity primary key,
 name varchar(80) not null,
 icon varchar(50) not null default 'fa-check-circle'
);
create table if not exists public.restriction_types (
 id smallint generated by default as identity primary key,
 name varchar(80) not null
);
create table if not exists public.parkings (
 id bigint generated by default as identity primary key,
 owner_id bigint not null references public.users(id),
 location_id bigint not null references public.locations(id),
 category_id smallint not null references public.parking_categories(id),
 name varchar(100) not null,
 description text not null,
 schedule jsonb not null default '{}'::jsonb,
 is_24_7 boolean not null default false,
 contact_name varchar(80),
 contact_phone varchar(30) not null,
 contact_email varchar(150),
 status text not null default 'activo' check (status in ('activo','inactivo')),
 is_private boolean not null default false,
 access_code varchar(12),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.parking_images (
 id bigint generated by default as identity primary key,
 parking_id bigint not null references public.parkings(id) on delete cascade,
 image_url text not null,
 sort_order smallint not null default 0,
 is_primary boolean not null default false,
 uploaded_at timestamptz not null default now()
);
create table if not exists public.parking_capacities (
 parking_id bigint primary key references public.parkings(id) on delete cascade,
 general_capacity integer not null,
 reservable_capacity integer,
 disability_spaces integer not null default 0,
 pregnant_people_spaces integer not null default 0,
 taxi_spaces integer not null default 0
);
create table if not exists public.parking_vehicle_capacities (
 parking_id bigint not null references public.parkings(id) on delete cascade,
 vehicle_type_id smallint not null references public.vehicle_types(id),
 capacity integer not null default 0,
 reservable_vehicle_c integer default 0,
 primary key (parking_id, vehicle_type_id)
);
create table if not exists public.parking_fees (
 id bigint generated by default as identity primary key,
 parking_id bigint not null references public.parkings(id) on delete cascade,
 vehicle_type_id smallint not null references public.vehicle_types(id),
 fee_type text not null default 'normal',
 price varchar(50) not null default 'Gratis',
 time_unit text not null default 'hora',
 applies_to text not null default 'Toda la semana',
 valid_from date,
 valid_to date
);
create table if not exists public.parking_services (
 parking_id bigint not null references public.parkings(id) on delete cascade,
 service_id smallint not null references public.services(id),
 primary key (parking_id, service_id)
);
create table if not exists public.parking_restrictions (
 parking_id bigint primary key references public.parkings(id) on delete cascade,
 max_height numeric(4,2),
 max_speed smallint
);
create table if not exists public.parking_restriction_items (
 parking_id bigint not null references public.parkings(id) on delete cascade,
 restriction_type_id smallint not null references public.restriction_types(id),
 primary key (parking_id, restriction_type_id)
);
create table if not exists public.reviews (
 id bigint generated by default as identity primary key,
 parking_id bigint not null references public.parkings(id) on delete cascade,
 user_id bigint not null references public.users(id),
 rating smallint not null check (rating between 1 and 5),
 comment text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create index if not exists idx_parkings_owner_id on public.parkings(owner_id);
create index if not exists idx_parkings_location_id on public.parkings(location_id);
create index if not exists idx_parkings_category_id on public.parkings(category_id);
create index if not exists idx_parking_images_parking_order on public.parking_images(parking_id, sort_order);
create index if not exists idx_parking_fees_parking on public.parking_fees(parking_id);
create index if not exists idx_parking_reviews_parking on public.reviews(parking_id);

