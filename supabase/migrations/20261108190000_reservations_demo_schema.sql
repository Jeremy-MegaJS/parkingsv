-- Reservations table used by the Parking SV demo application.
-- Access is restricted to server-side service_role operations.

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  parking_id bigint not null references public.parkings(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  vehicle_type_id smallint not null references public.vehicle_types(id),
  fechahorainicio timestamptz not null,
  fechahorafin timestamptz not null,
  codigo_qr text not null unique,
  status text not null default 'reservado'
    check (status in ('reservado', 'cancelado', 'usado', 'sancionado')),
  created_at timestamptz not null default now(),
  constraint reservations_valid_time check (fechahorafin > fechahorainicio)
);

create index if not exists idx_reservations_user_start
  on public.reservations(user_id, fechahorainicio desc);
create index if not exists idx_reservations_parking_start
  on public.reservations(parking_id, fechahorainicio desc);

alter table public.reservations enable row level security;
revoke all on public.reservations from anon, authenticated;
grant all on public.reservations to service_role;
grant usage, select on sequence public.reservations_id_seq to service_role;
